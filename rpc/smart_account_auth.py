def _rpc_url() -> str:
    return os.environ.get("ARC_RPC_URL", "https://rpc.testnet.arc.network").strip()


def eip191_message_hash(message: str) -> bytes:
    payload = message.encode("utf-8")
    prefix = b"\x19Ethereum Signed Message:\n" + str(len(payload)).encode("ascii")
    return Web3.keccak(prefix + payload)


def verify_message_signature(address: str, message: str, signature: str) -> bool:
    """Return True only when ``signature`` is valid for ``address``.

    The check is performed by an ERC-6492 aware validator through a read-only
    Arc RPC ``eth_call``.  Any RPC/decoding error is a failed authentication,
    never an implicit success.
    """
    try:
        if not Web3.is_address(address):
            return False
        if not isinstance(signature, str) or not signature.startswith("0x"):
            return False

        signer = Web3.to_checksum_address(address)
        digest = eip191_message_hash(message)
        sig_bytes = bytes.fromhex(signature[2:])
        constructor_args = encode(["address", "bytes32", "bytes"], [signer, digest, sig_bytes])
        call_data = bytes.fromhex(_ERC6492_VALIDATOR_BYTECODE[2:]) + constructor_args

        w3 = Web3(Web3.HTTPProvider(_rpc_url(), request_kwargs={"timeout": 20}))
        result = w3.eth.call({"data": "0x" + call_data.hex()})
        return bool(result) and int.from_bytes(result, byteorder="big") == 1
    except Exception as exc:
        print(f"    [AUTH] Smart-account signature verification failed: {exc}")
        return False
